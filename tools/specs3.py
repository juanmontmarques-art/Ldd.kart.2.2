# ================= CUME (hardcore) : estrada alpina com espiral, pontes entre penhascos, paredes
def spiral(cx, cz, r0, r1, a0, step, n, Rf=0.86):
    out = []
    for k in range(n+1):
        th = math.radians(a0+step*k)
        r = r0+(r1-r0)*k/n
        R = Rf*r*math.cos(math.radians(abs(step))/2)
        out.append((round(cx+r*math.cos(th)), round(cz+r*math.sin(th)), round(R)))
    return out

